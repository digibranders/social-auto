import assert from 'node:assert/strict';
import { mkdtemp, rm, utimes, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { createScheduleSource, parseScheduleModule } from './schedule-source.ts';

const header = '// Generated by scheduler/engine/src/export-publisher.ts. Do not edit by hand.\n';
const moduleText = (posts: unknown[]): string => `${header}export const schedule = ${JSON.stringify({ posts }, null, 2)};\n`;
const post = (id: string) => ({ id, date: '2026-11-09T10:00:00+05:30', caption: 'Hello; "quoted" } {braces}', image: null });

test('parseScheduleModule reads the generated module, including braces and semicolons inside captions', () => {
  assert.deepEqual(parseScheduleModule(moduleText([post('a')])), { posts: [post('a')] });
});

test('parseScheduleModule refuses a file that is not the generated module', () => {
  assert.throws(() => parseScheduleModule('export const other = 1;'), /schedule/);
  assert.throws(() => parseScheduleModule('export const schedule = { nope'), /schedule/);
});

test('without a file the bundled data is used', () => {
  const bundled = { posts: [post('bundled')] };
  assert.equal(createScheduleSource(undefined, bundled).current(), bundled);
  assert.deepEqual(createScheduleSource(undefined, bundled).data.posts, bundled.posts);
});

test('with a file the latest version is read, and reloaded only when the file changes', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'schedule-test-'));
  try {
    const file = join(dir, 'schedule.ts');
    await writeFile(file, moduleText([post('one')]));
    let reads = 0;
    const source = createScheduleSource(file, { posts: [] }, () => void (reads += 1));
    assert.deepEqual(source.data.posts, [post('one')]);
    source.current();
    assert.equal(reads, 1, 'unchanged file is not read again');

    await writeFile(file, moduleText([post('one'), post('two')]));
    const later = new Date(Date.now() + 5_000);
    await utimes(file, later, later);
    assert.equal((source.data.posts as unknown[]).length, 2);
    assert.equal(reads, 2);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('a broken new version keeps serving the last good one and reports the problem', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'schedule-test-'));
  try {
    const file = join(dir, 'schedule.ts');
    await writeFile(file, moduleText([post('good')]));
    const problems: string[] = [];
    const source = createScheduleSource(file, { posts: [] }, undefined, (m) => problems.push(m));
    assert.deepEqual(source.data.posts, [post('good')]);
    await writeFile(file, 'export const schedule = { broken');
    const later = new Date(Date.now() + 5_000);
    await utimes(file, later, later);
    assert.deepEqual(source.data.posts, [post('good')]);
    assert.equal(problems.length, 1);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('a missing file at start is an error, not an empty schedule', () => {
  assert.throws(() => createScheduleSource('/nonexistent/schedule.ts', { posts: [] }).current(), /schedule/i);
});
