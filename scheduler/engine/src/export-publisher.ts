/**
 * Copies rendered posters and captions into the Vercel publisher so it can post without this Mac.
 * Every post ever planned stays in the schedule, so the dashboard can show any past week. Only
 * upcoming and recent posts keep their poster; older ones are exported with `image: null`, which
 * keeps the deployment from growing forever.
 *
 * Posters are public (Instagram downloads them) but named by a hash of their content, so URLs
 * cannot be guessed. The schedule is written to publisher/data/schedule.ts, which the posting
 * function imports, so it is bundled with it and never served as a public file.
 *
 *   node src/export-publisher.ts --brand brands/brandbasket [--publisher ../../publisher]
 */
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { composeCaption, isPublishable, parseWeekPlan, readJson } from './content.ts';
import { assertPublishingEnabled } from './publishing-switch.ts';
import { ReviewError, ReviewStore } from './review-store.ts';

const WEEK_FILE = /^week-\d+\.json$/;
/** Posters are kept for posts from the last 20 hours onwards, so a post due today can still be published. */
const KEEP_RECENT_MS = 20 * 60 * 60 * 1000;

export interface ExportedPost {
  brand: string;
  id: string;
  date: string;
  caption: string;
  /** Poster path in the publisher, or null once the poster was pruned. For a carousel, the first slide. */
  image: string | null;
  /** A carousel: every slide's picture in order (two to ten); `image` is the first. Absent for a single picture. */
  images?: string[];
  /** The platforms the owner chose for this client's campaign ("instagram", "facebook", ...); missing means every connected channel. */
  channels?: string[];
  /** Made from a client's posting plan: the publisher sends it only to that client's own connected channels, never to the team's one shared Instagram account. */
  fromPlan?: true;
  /** A caption and/or picture of its own for single networks (the publisher's "variants"): the main caption and picture stand for the rest. */
  variants?: Record<string, { caption?: string; image?: string }>;
  /** Sent at its own time by the frequent run (every few minutes), not left to the once-a-day run, so a time other than 10:00 is honoured. */
  ownTime?: true;
}

/** 128-bit content hash: stable for the same image, unguessable without it. */
export function posterFileName(image: Buffer): string {
  return `${createHash('sha256').update(image).digest('hex').slice(0, 32)}.jpg`;
}

/**
 * The schedule is a generated TypeScript module: the cron function imports it, so it is always
 * bundled with the function and never served as a public file.
 */
const SCHEDULE_FILE = join('data', 'schedule.ts');
const SCHEDULE_PREFIX = '// Generated by scheduler/engine/src/export-publisher.ts. Do not edit by hand.\nexport const schedule = ';
const SCHEDULE_SUFFIX = ';\n';

export function scheduleModule(posts: ExportedPost[]): string {
  return `${SCHEDULE_PREFIX}${JSON.stringify({ posts }, null, 2)}${SCHEDULE_SUFFIX}`;
}

export function parseScheduleModule(source: string): ExportedPost[] {
  if (!source.startsWith(SCHEDULE_PREFIX) || !source.endsWith(SCHEDULE_SUFFIX)) {
    throw new Error(`${SCHEDULE_FILE} was not generated by export-publisher`);
  }
  const json = source.slice(SCHEDULE_PREFIX.length, -SCHEDULE_SUFFIX.length);
  return (JSON.parse(json) as { posts: ExportedPost[] }).posts;
}

async function readSchedule(path: string): Promise<ExportedPost[]> {
  try {
    return parseScheduleModule(await readFile(path, 'utf8'));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
}

/**
 * Where the plan a week file was made for posts, from the campaign runner's records (brands/<site>/campaigns/*.json): the exact account for each platform
 * the plan was bound to, and the bare platform for one it was not (the publisher then sends only if the client has a single account there).
 * undefined for a week file no campaign made (it then goes to every connected channel, as before plans existed).
 */
async function platformsForWeek(brandDir: string, weekFile: string): Promise<string[] | undefined> {
  let names: string[];
  try {
    names = (await readdir(join(brandDir, 'campaigns'))).filter((f) => f.endsWith('.json'));
  } catch {
    return undefined;
  }
  for (const name of names) {
    try {
      const state = JSON.parse(await readFile(join(brandDir, 'campaigns', name), 'utf8')) as { plan?: { platforms?: unknown; channelIds?: unknown }; batches?: Array<{ weekFile?: unknown }> };
      const platforms = state.plan?.platforms;
      if (state.batches?.some((b) => b.weekFile === weekFile) && Array.isArray(platforms) && platforms.length > 0 && platforms.every((p) => typeof p === 'string')) {
        const ids = Array.isArray(state.plan?.channelIds) ? (state.plan?.channelIds as unknown[]).filter((id): id is string => typeof id === 'string') : [];
        return (platforms as string[]).map((platform) => ids.find((id) => id.startsWith(`${platform}:`)) ?? platform);
      }
    } catch {
      // An unreadable record is skipped; the post then follows the default rather than a guess.
    }
  }
  return undefined;
}

/** The network whose version is the post's main caption and picture when it was made per network (the square picture most networks share comes first). */
const MAIN_NETWORK_ORDER = ['instagram', 'facebook', 'google', 'linkedin'];

type ApprovedVersion = ReturnType<ReviewStore['approvedFor']> & object;

/**
 * The approved versions of a post made per network, one per network (the latest if there were several), limited to the networks the plan may go to.
 * Empty when the post was not made per network (an older poster approved as a whole).
 */
function approvedPerNetwork(store: ReviewStore, postId: string, platforms: string[] | undefined): Map<string, ApprovedVersion> {
  const byNetwork = new Map<string, ApprovedVersion>();
  for (const item of [...store.approvedForNetworks(postId)].sort((a, b) => a.version.versionNumber - b.version.versionNumber)) {
    const network = item.version.network;
    // The plan's entries are the platform alone or, once bound, "platform:account"; either way the network is the part before the colon.
    if (network !== undefined && (!platforms || platforms.some((p) => p.split(':')[0] === network))) byNetwork.set(network, item);
  }
  return byNetwork;
}

export interface ExportOptions {
  /**
   * The client's own name, when it is not the site folder's (a client "fynix-digital" whose site folder is "fynix"). The posts are filed under it, because a
   * client's channels belong to the client: filed under the folder's name they would match no channel and be sent nowhere.
   */
  brand?: string;
  /** Only these week files are exported: the ones this client's plans made. */
  weekFiles?: readonly string[];
}

export async function exportToPublisher(brandDir: string, publisherDir: string, now = Date.now(), options: ExportOptions = {}): Promise<ExportedPost[]> {
  // The publisher app sends what it is given to the platforms, so handing it posts is publishing: refused (and nothing is written) while the switch is off.
  assertPublishingEnabled('exporting to the publisher');
  /** The site folder: the review queue and the picture folders are named after it. */
  const site = basename(brandDir);
  /** The client the posts are for. */
  const brand = options.brand ?? site;
  const postsDir = join(publisherDir, 'public', 'posts', brand);
  await rm(postsDir, { recursive: true, force: true });
  await mkdir(postsDir, { recursive: true });
  await mkdir(join(publisherDir, 'data'), { recursive: true });

  const exported: ExportedPost[] = [];
  const files = (await readdir(brandDir)).filter((f) => WEEK_FILE.test(f) && (options.weekFiles === undefined || options.weekFiles.includes(f))).sort();
  for (const file of files) {
    const plan = parseWeekPlan(await readJson(join(brandDir, file)), file);
    const platforms = await platformsForWeek(brandDir, file);
    // A site the campaign runner manages must trace every AI poster to a plan, because the plan says where it may go. One that
    // cannot be traced (its record is gone) is held back rather than sent to every connected channel.
    if (plan.renderMode === 'ai_v1' && !platforms && existsSync(join(brandDir, 'campaigns'))) {
      console.warn(`${brand}: ${file} is not tied to any posting plan, so its posters were not exported`);
      continue;
    }
    const outDir = resolve('out', site, basename(file, '.json'));
    const store = new ReviewStore(brandDir, site);
    for (const post of plan.posts) {
      // A carousel goes out only as a whole: every slide approved as it is now. One that is not is skipped, never sent as its cover alone.
      let slides: ApprovedVersion[] | undefined;
      if (plan.renderMode === 'ai_v1' && store.isCarousel(post.id)) {
        try {
          slides = store.approvedCarousel(post.id).slides;
        } catch (error) {
          if (error instanceof ReviewError && error.code === 'NOT_APPROVED') continue;
          throw error;
        }
      }
      // Fully AI posters are exported only as the exact approved version (its picture and its caption); every other plan by its own approval.
      const perNetwork = plan.renderMode === 'ai_v1' ? approvedPerNetwork(store, post.id, platforms) : new Map<string, ApprovedVersion>();
      const approved = plan.renderMode === 'ai_v1' ? (perNetwork.size > 0 ? perNetwork.get(MAIN_NETWORK_ORDER.find((n) => perNetwork.has(n)) ?? '') : store.approvedFor(post.id)) : undefined;
      if (plan.renderMode === 'ai_v1' ? !approved : !isPublishable(plan, post)) continue;
      const recent = Date.parse(post.date) >= now - KEEP_RECENT_MS;
      const place = async (image: Buffer): Promise<string | null> => {
        if (!recent) return null;
        const fileName = posterFileName(image);
        await writeFile(join(postsDir, fileName), image);
        return `/posts/${brand}/${fileName}`;
      };
      const mainBytes = approved ? approved.bytes : await readFile(join(outDir, `${post.id}.jpg`));
      const poster = await place(mainBytes);
      const slidePaths = slides ? await Promise.all(slides.map((slide) => place(slide.bytes))) : [];
      // A post made per network goes only to the networks whose own picture and caption were approved; each keeps its own caption, and its own picture when it differs.
      const variants: NonNullable<ExportedPost['variants']> = {};
      if (approved && perNetwork.size > 0) {
        for (const [network, item] of perNetwork) {
          const sameImage = item.bytes.equals(approved.bytes);
          const sameCaption = item.version.caption === approved.version.caption;
          if (sameImage && sameCaption) continue;
          const image = sameImage ? null : await place(item.bytes);
          variants[network] = { ...(sameCaption ? {} : { caption: item.version.caption }), ...(image ? { image } : {}) };
        }
      }
      // Where each approved network goes: the exact account the plan was bound to, or the bare network when it was not.
      const channels = perNetwork.size > 0 ? [...perNetwork.keys()].map((n) => platforms?.find((p) => p.startsWith(`${n}:`)) ?? n) : platforms;
      exported.push({
        brand,
        id: `${brand}-${post.id}`,
        date: post.date,
        caption: approved ? approved.version.caption : composeCaption(post),
        image: slidePaths.length > 0 && slidePaths.every((p) => p !== null) ? slidePaths[0] ?? null : poster,
        ...(slidePaths.length > 0 && slidePaths.every((p): p is string => p !== null) ? { images: slidePaths } : {}),
        // A fully AI poster goes only to the platforms the owner chose (and, when it was made per network, only those approved); every other plan keeps going to every connected channel.
        ...(approved && channels ? { channels, ...(platforms ? { fromPlan: true as const } : {}) } : {}),
        ...(Object.keys(variants).length > 0 ? { variants } : {}),
        // A fully AI poster has the time its plan chose; the frequent run sends it then (the daily run would send one set for the afternoon the next morning).
        ...(approved ? { ownTime: true as const } : {}),
      });
    }
  }

  // The schedule is shared by all brands: replace only this brand's entries.
  const schedulePath = join(publisherDir, SCHEDULE_FILE);
  // Entries an earlier version filed under the site folder's name (which no channel matches) are cleared, so a client does not show up twice.
  const strayFromPlans = (p: { brand?: string; id: string; ownTime?: boolean }): boolean => brand !== site && p.brand === site && p.ownTime === true && p.id.startsWith(`${site}-w`);
  const others = (await readSchedule(schedulePath)).filter((p) => p.brand !== brand && !strayFromPlans(p));
  const merged = [...others, ...exported].sort((a, b) => Date.parse(a.date) - Date.parse(b.date));
  await writeFile(schedulePath, scheduleModule(merged));
  await rm(join(publisherDir, 'public', 'schedule.json'), { force: true });
  await rm(join(publisherDir, 'data', 'schedule.json'), { force: true });
  return exported;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      brand: { type: 'string' },
      publisher: { type: 'string', default: '../../publisher' },
    },
  });
  if (!values.brand) throw new Error('Usage: --brand <dir> [--publisher <dir>]');
  const posts = await exportToPublisher(resolve(values.brand), resolve(values.publisher));
  const first = posts[0]?.date ?? '-';
  const last = posts.at(-1)?.date ?? '-';
  const withPosters = posts.filter((p) => p.image !== null).length;
  console.log(`Exported ${posts.length} posts (${first} → ${last}), ${withPosters} with posters`);
}

if (import.meta.main) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? `${error.name}: ${error.message}` : error);
    process.exitCode = 1;
  });
}
